// Anthropic 余额耗尽返回 400，而 400 不在默认重试状态码区间内。
// 判定收敛到 operation_setting.IsUpstreamExhaustedError（与渠道自动禁用同一套关键词），
// 这里确认解析后的错误能被它识别，否则下游用户会直接收到余额错误而不会换渠道。
func TestRelayErrorHandlerUpstreamQuotaIsDetectable(t *testing.T) {
	body := `{"type":"error","error":{"type":"invalid_request_error","message":"Your credit balance is too low to access the Anthropic API. Please go to Plans \u0026 Billing to upgrade or purchase credits."}}`
	resp := &http.Response{
		StatusCode: http.StatusBadRequest,
		Body:       io.NopCloser(strings.NewReader(body)),
	}

	newAPIError := RelayErrorHandler(context.Background(), resp, false)

	require.NotNil(t, newAPIError)
	require.True(t, operation_setting.IsUpstreamExhaustedError(newAPIError),
		"必须被识别为上游额度耗尽，才能跨过 400 不重试的默认区间")
	require.Equal(t, http.StatusBadRequest, newAPIError.StatusCode, "保留上游状态码便于排查")
	require.Contains(t, newAPIError.Error(), "credit balance is too low")
}

// 与上一条互为对照：同样是 400，普通参数错误不能被判成额度耗尽，
// 否则会触发无意义的跨渠道重试并可能误禁用健康渠道。
func TestRelayErrorHandlerKeepsOrdinaryBadRequestUnmarked(t *testing.T) {
	body := `{"type":"error","error":{"type":"invalid_request_error","message":"max_tokens: 999999 > 8192, which is the maximum allowed number of output tokens"}}`
	resp := &http.Response{
		StatusCode: http.StatusBadRequest,
		Body:       io.NopCloser(strings.NewReader(body)),
	}

	newAPIError := RelayErrorHandler(context.Background(), resp, false)

	require.NotNil(t, newAPIError)
	require.False(t, types.IsChannelError(newAPIError))
	require.False(t, operation_setting.IsUpstreamExhaustedError(newAPIError),
		"普通参数错误不能被判成额度耗尽")
}

